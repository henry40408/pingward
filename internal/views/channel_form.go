package views

// ChannelFormView feeds the new and edit channel forms.
type ChannelFormView struct {
	CSRF          string
	IsAdmin       bool
	Admin         bool // the form lives under /admin
	ProjectID     int64
	Error         string // empty = none
	SMTPAvailable bool
	Edit          *ChannelEditView // nil when creating
}

// ChannelEditView is the edit page's only view of a stored config, so a secret
// cannot leak by type. Webhook and Slack URLs are capability secrets; chat ids,
// ntfy server and topic, and email recipients are safe to pre-fill.
type ChannelEditView struct {
	ID   int64
	Kind string
	Name string
	// Pre-filled, non-secret.
	TelegramChatID string
	NtfyBaseURL    string
	NtfyTopic      string
	EmailTo        string
	// Configured or not-set pills only.
	HasWebhookURL    bool
	HasSlackURL      bool
	HasTelegramToken bool
	HasNtfyToken     bool
	HasPushoverToken bool
	HasPushoverUser  bool
}

// secretStatus never re-renders a secret, only whether one is stored.
func secretStatus(isSet bool) node {
	status := el("span", []attr{a("class", "note")}, text("not set"))
	if isSet {
		status = el("span", []attr{a("class", "pill ok")}, text("configured"))
	}
	return el("div", []attr{a("class", "help")}, status, text(" — leave blank to keep the stored value."))
}

func ChannelForm(v ChannelFormView) string {
	base := ""
	if v.Admin {
		base = "/admin"
	}
	editing := v.Edit != nil
	// Empty when creating: every block renders and app.css's :has() rules show the
	// selected kind's. When editing, only the immutable kind's.
	kind, name, heading, submit := "", "", "New channel", "Create channel"
	action := base + "/projects/" + num(v.ProjectID) + "/channels"
	if editing {
		kind, name, heading, submit = v.Edit.Kind, v.Edit.Name, "Edit channel", "Save changes"
		action = base + "/channels/" + num(v.Edit.ID)
	}
	creating := !editing
	body := group(
		el("h1", nil, text(heading)),
		when(v.Error != "", el("p", []attr{a("class", "flash err")}, text(v.Error))),
		el("div", []attr{a("class", "card")}, el("div", []attr{a("class", "cb")},
			el("form", []attr{a("method", "post"), a("action", action)},
				CSRFField(v.CSRF),
				el("div", []attr{a("class", "field")},
					el("label", []attr{a("for", "name")}, text("Name")),
					void("input", a("id", "name"), a("name", "name"), flag("required"), attrIf(editing, "value", name))),
				el("div", []attr{a("class", "field")},
					el("label", []attr{a("for", "kind")}, text("Kind")),
					channelKindField(v)),
				when(creating || kind == "webhook", webhookBlock(v.Edit)),
				when(creating || kind == "slack", slackBlock(v.Edit)),
				when(creating || kind == "telegram", telegramBlock(v.Edit)),
				when(creating || kind == "ntfy", ntfyBlock(v.Edit)),
				when(creating || kind == "pushover", pushoverBlock(v.Edit)),
				// Editable even with SMTP off; only creation is gated on it.
				when(kind == "email" || (creating && v.SMTPAvailable), emailBlock(v.Edit)),
				el("div", []attr{a("class", "btnrow")},
					el("button", []attr{a("class", "btn primary"), a("type", "submit")}, text(submit)),
					when(editing, el("a", []attr{a("class", "btn"), a("href", base+"/projects/"+num(v.ProjectID))}, text("Cancel")))),
			))),
	)
	return Page(navChrome(v.IsAdmin, v.CSRF), body)
}

func channelKindField(v ChannelFormView) node {
	if v.Edit != nil {
		return group(
			el("p", []attr{a("class", "mono"), a("data-testid", "channel-kind-static")}, text(v.Edit.Kind)),
			el("div", []attr{a("class", "help")}, text("A channel's kind can't be changed — delete it and create a new one instead.")))
	}
	option := func(kind string) node {
		return el("option", []attr{a("value", kind)}, text(kind))
	}
	return el("select", []attr{a("name", "kind"), a("id", "kind")},
		option("webhook"), option("slack"), option("telegram"), option("ntfy"), option("pushover"),
		when(v.SMTPAvailable, option("email")))
}

func unchangedIf(editing bool) attr { return attrIf(editing, "placeholder", "unchanged") }

func configBlock(kind string, fields ...node) node {
	return el("div", []attr{a("class", "cfg"), a("data-kind", kind)}, fields...)
}

func webhookBlock(edit *ChannelEditView) node {
	editing := edit != nil
	return configBlock("webhook", el("div", []attr{a("class", "field")},
		el("label", []attr{a("for", "webhook_url")}, text("Webhook URL")),
		void("input", a("id", "webhook_url"), a("name", "webhook_url"), attrIf(editing, "class", "mono"), unchangedIf(editing)),
		when(editing, secretStatus(editing && edit.HasWebhookURL))))
}

func slackBlock(edit *ChannelEditView) node {
	placeholder := "https://hooks.slack.com/services/..."
	status := el("div", []attr{a("class", "help")}, text("Paste the incoming webhook URL generated by your Slack app."))
	if edit != nil {
		placeholder = "unchanged"
		status = secretStatus(edit.HasSlackURL)
	}
	return configBlock("slack", el("div", []attr{a("class", "field")},
		el("label", []attr{a("for", "slack_url")}, text("Slack incoming webhook URL")),
		void("input", a("id", "slack_url"), a("name", "slack_url"), a("class", "mono"), a("placeholder", placeholder)),
		status))
}

func telegramBlock(edit *ChannelEditView) node {
	editing := edit != nil
	chatID := ""
	if editing {
		chatID = edit.TelegramChatID
	}
	return configBlock("telegram",
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "telegram_token")}, text("Bot token")),
			void("input", a("id", "telegram_token"), a("name", "telegram_token"), unchangedIf(editing)),
			when(editing, secretStatus(editing && edit.HasTelegramToken))),
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "telegram_chat_id")}, text("Chat id")),
			void("input", a("id", "telegram_chat_id"), a("name", "telegram_chat_id"), attrIf(editing, "value", chatID))))
}

func ntfyBlock(edit *ChannelEditView) node {
	editing := edit != nil
	baseURL, topic, hasToken := "", "", false
	if editing {
		baseURL, topic, hasToken = edit.NtfyBaseURL, edit.NtfyTopic, edit.HasNtfyToken
	}
	return configBlock("ntfy",
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "ntfy_base_url")}, text("Server base URL")),
			void("input", a("id", "ntfy_base_url"), a("name", "ntfy_base_url"), a("placeholder", "https://ntfy.sh"), attrIf(editing, "value", baseURL))),
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "ntfy_topic")}, text("Topic")),
			void("input", a("id", "ntfy_topic"), a("name", "ntfy_topic"), attrIf(editing, "value", topic))),
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "ntfy_token")}, text("Token (optional)")),
			void("input", a("id", "ntfy_token"), a("name", "ntfy_token"), unchangedIf(editing)),
			when(editing, group(
				secretStatus(hasToken),
				// Blank keeps the stored token, so removing it needs this.
				when(hasToken, el("label", []attr{a("class", "chk")},
					void("input", a("type", "checkbox"), a("name", "ntfy_token_clear"), a("value", "true"), a("data-testid", "ntfy-token-clear")),
					el("span", []attr{a("class", "nm")}, text("Remove the stored token"))))))))
}

func pushoverBlock(edit *ChannelEditView) node {
	editing := edit != nil
	hasToken, hasUser := false, false
	if editing {
		hasToken, hasUser = edit.HasPushoverToken, edit.HasPushoverUser
	}
	return configBlock("pushover",
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "pushover_token")}, text("Application token")),
			void("input", a("id", "pushover_token"), a("name", "pushover_token"), unchangedIf(editing)),
			when(editing, secretStatus(hasToken))),
		el("div", []attr{a("class", "field")},
			el("label", []attr{a("for", "pushover_user")}, text("User/group key")),
			void("input", a("id", "pushover_user"), a("name", "pushover_user"), unchangedIf(editing)),
			when(editing, secretStatus(hasUser))))
}

func emailBlock(edit *ChannelEditView) node {
	to := ""
	if edit != nil {
		to = edit.EmailTo
	}
	return configBlock("email", el("div", []attr{a("class", "field")},
		el("label", []attr{a("for", "email_to")}, text("Recipient email")),
		void("input", a("id", "email_to"), a("name", "email_to"), a("type", "email"), attrIf(edit != nil, "value", to))))
}
