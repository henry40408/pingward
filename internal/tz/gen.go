//go:build ignore

// gen turns testdata/chrono_tz_names.txt (chrono_tz::TZ_VARIANTS, captured from
// Rust) into names.go. Run: go run gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	input, err := os.Open("testdata/chrono_tz_names.txt")
	if err != nil {
		panic(err)
	}
	defer input.Close()

	var out strings.Builder
	out.WriteString("// Code generated by gen.go from testdata/chrono_tz_names.txt; DO NOT EDIT.\n\npackage tz\n\n")
	out.WriteString("// names is chrono_tz::TZ_VARIANTS in Rust's order.\nvar names = []string{\n")
	scanner := bufio.NewScanner(input)
	for scanner.Scan() {
		fmt.Fprintf(&out, "\t%q,\n", scanner.Text())
	}
	out.WriteString("}\n")
	if err := os.WriteFile("names.go", []byte(out.String()), 0o644); err != nil {
		panic(err)
	}
}
